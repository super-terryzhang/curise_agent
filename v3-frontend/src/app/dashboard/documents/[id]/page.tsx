/**
 * Build the breadcrumb path from leaf → root by walking parent_folder_id.
 * Returns ordered list root-first. Cycle-safe (capped at depth 12).
 */
function buildFolderPath(
  leafId: number | null,
  folders: DocumentFolder[],
): DocumentFolder[] {
  if (leafId == null) return [];
  const byId = new Map<number, DocumentFolder>();
  for (const f of folders) byId.set(f.id, f);
  const path: DocumentFolder[] = [];
  let cur: DocumentFolder | undefined = byId.get(leafId);
  const seen = new Set<number>();
  let safety = 0;
  while (cur && !seen.has(cur.id) && safety < 12) {
    seen.add(cur.id);
    path.unshift(cur);
    cur = cur.parent_folder_id != null ? byId.get(cur.parent_folder_id) : undefined;
    safety++;
  }
  return path;
}

// DocumentFolderPicker — shows the full breadcrumb path (P3B-F4
// 2026-06-22 UX) and lets the user move the doc. Pre-loads folders
// on mount so the breadcrumb renders immediately rather than the
// previous "Folder Name only after dropdown opens" pattern.
function DocumentFolderPicker({
  doc,
  onMoved,
}: {
  doc: DocumentDetail;
  onMoved: (updated: DocumentDetail) => void;
}) {
  const [folders, setFolders] = useState<DocumentFolder[]>([]);
  const [open, setOpen] = useState(false);
  const [moving, setMoving] = useState(false);

  // Preload folders so the breadcrumb is correct on first paint.
  // Cheap call — list is bounded.
  useEffect(() => {
    listFolders().then(setFolders).catch(() => {});
  }, []);

  const path = buildFolderPath(doc.folder_id, folders);

  const move = async (target: number | null) => {
    if (target === doc.folder_id) return;
    setMoving(true);
    try {
      const updated = await moveDocumentToFolder(doc.id, target);
      onMoved(updated);
      const targetLabel =
        target === null
          ? "未分类"
          : folders.find((f) => f.id === target)?.name ?? "目标文件夹";
      toast.success(`已移动到「${targetLabel}」`);
      setOpen(false);
    } catch (err) {
      toast.error(err instanceof Error ? err.message : "移动失败");
    } finally {
      setMoving(false);
    }
  };

  return (
    <DropdownMenu open={open} onOpenChange={setOpen}>
      <DropdownMenuTrigger asChild>
        <button
          className="mt-2 inline-flex items-center gap-0.5 text-[11px] text-muted-foreground hover:text-foreground transition-colors disabled:opacity-50 max-w-full"
          disabled={moving}
          title="移动到文件夹"
        >
          <Folder className="h-3 w-3 shrink-0 mr-0.5" />
          {path.length === 0 ? (
            <span className="truncate">未分类</span>
          ) : (
            path.map((f, i) => {
              const dot = folderColor(f);
              return (
                <span key={f.id} className="inline-flex items-center min-w-0 gap-1">
                  {i > 0 && (
                    <span className="mx-0.5 text-muted-foreground/40 shrink-0">
                      ›
                    </span>
                  )}
                  {dot ? (
                    <span
                      className="inline-block h-1.5 w-1.5 shrink-0 rounded-full"
                      style={{ backgroundColor: dot }}
                      aria-hidden
                    />
                  ) : null}
                  <span className="truncate max-w-[120px]" title={f.name}>
                    {f.name}
                  </span>
                </span>
              );
            })
          )}
          <ChevronDown className="h-3 w-3 shrink-0 ml-0.5" />
        </button>
      </DropdownMenuTrigger>
      <DropdownMenuContent align="start" className="max-h-[300px] overflow-y-auto w-56">
        <DropdownMenuItem onClick={() => move(null)}>
          <Folder className="mr-1.5 h-3 w-3 text-muted-foreground/40" />
          <span className="text-muted-foreground">未分类</span>
          {doc.folder_id === null && <Check className="ml-auto h-3 w-3" />}
        </DropdownMenuItem>
        {folders.length === 0 ? (
          <div className="px-2 py-1.5 text-[11px] text-muted-foreground/60">
            还没有文件夹
          </div>
        ) : (
          folders.map((f) => {
            const dot = folderColor(f);
            return (
              <DropdownMenuItem key={f.id} onClick={() => move(f.id)}>
                {dot ? (
                  <span
                    className="mr-1.5 inline-block h-2 w-2 shrink-0 rounded-full"
                    style={{ backgroundColor: dot }}
                    aria-hidden
                  />
                ) : (
                  <Folder className="mr-1.5 h-3 w-3 text-muted-foreground/70" />
                )}
                <span className="truncate">{f.name}</span>
                {doc.folder_id === f.id && <Check className="ml-auto h-3 w-3" />}
              </DropdownMenuItem>
            );
          })
        )}
      </DropdownMenuContent>
    </DropdownMenu>
  );
}


// EditableDocTitle — title shows `display_name ?? filename` with a click
// affordance to rename. Esc cancels, Enter saves, blur saves. Empty
// input clears `display_name`, which reverts to filename. The original
// filename is always visible as a smaller line below the title so the
// audit trail isn't lost when a user renames.
function EditableDocTitle({
  doc,
  onSaved,
}: {
  doc: DocumentDetail;
  onSaved: (updated: DocumentDetail) => void;
}) {
  const [editing, setEditing] = useState(false);
  const [draft, setDraft] = useState(doc.display_name ?? "");
  const [saving, setSaving] = useState(false);
  const renamed = !!doc.display_name && doc.display_name !== doc.filename;

  const commit = async () => {
    if (saving) return;
    const next = draft.trim();
    // No-op if nothing changed (covers "open editor, click away").
    const before = (doc.display_name ?? "").trim();
    if (next === before) {
      setEditing(false);
      return;
    }
    setSaving(true);
    try {
      const updated = await renameDocument(doc.id, next || null);
      onSaved(updated);
      setEditing(false);
    } catch (err) {
      toast.error(err instanceof Error ? err.message : "重命名失败");
    } finally {
      setSaving(false);
    }
  };

  if (editing) {
    return (
      <div>
        <Input
          autoFocus
          value={draft}
          onChange={(e) => setDraft(e.target.value)}
          onBlur={() => void commit()}
          onKeyDown={(e) => {
            if (e.key === "Enter") {
              e.preventDefault();
              void commit();
            } else if (e.key === "Escape") {
              setDraft(doc.display_name ?? "");
              setEditing(false);
            }
          }}
          maxLength={255}
          placeholder={doc.filename}
          className="h-8 text-base font-semibold"
          disabled={saving}
        />
        <p className="mt-1 text-[11px] text-muted-foreground/70">
          Enter 保存，Esc 取消，留空恢复原文件名
        </p>
      </div>
    );
  }

  return (
    <div className="group">
      <button
        onClick={() => {
          setDraft(doc.display_name ?? "");
          setEditing(true);
        }}
        className="w-full text-left"
        title="点击重命名"
      >
        <h1 className="break-all text-base font-semibold leading-snug hover:text-foreground/80 transition-colors">
          {doc.display_name || doc.filename}
          <Pencil className="ml-1 inline h-3 w-3 text-muted-foreground/40 group-hover:text-muted-foreground transition-colors" />
        </h1>
      </button>
      {renamed && (
        <p
          className="mt-0.5 break-all text-[11px] text-muted-foreground/60"
          title="原文件名（不可修改）"
        >
          {doc.filename}
        </p>
      )}
    </div>
  );
}
