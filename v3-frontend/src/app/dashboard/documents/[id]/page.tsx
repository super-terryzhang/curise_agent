// ─── DocumentSummaryCard — AI summary + tag chips ────────────────────────
//
// Three chip styles, ordered by intent:
//   • System tags (`key:value` shape, e.g. `file_type:pdf`) — muted/mono.
//     Deterministic, derived from doc columns.
//   • LLM topic tags (bare strings, e.g. `celebrity-cruise`) — light bg.
//     Generated by the summarizer (regenerated on re-extract).
//   • User tags (manually added) — blue with X button to remove.
//     Survive re-extract. Add via the "+ 添加" input below.
//
// `summary` is rendered as plain prose paragraphs (the model is asked
// to return prose without markdown formatting).

function DocumentSummaryCard({
  summary,
  tags,
  userTags,
  onAddTag,
  onRemoveTag,
}: {
  summary: string | null;
  tags: string[];
  userTags: string[];
  onAddTag: (tag: string) => Promise<void>;
  onRemoveTag: (tag: string) => Promise<void>;
}) {
  const systemTags = tags.filter((t) => t.includes(":"));
  const topicTags = tags.filter((t) => !t.includes(":"));
  const [adding, setAdding] = useState(false);
  const [draft, setDraft] = useState("");
  const [pending, setPending] = useState(false);

  async function handleSubmit(e?: React.FormEvent) {
    if (e) e.preventDefault();
    const value = draft.trim();
    if (!value) {
      setAdding(false);
      return;
    }
    setPending(true);
    try {
      await onAddTag(value);
      setDraft("");
      setAdding(false);
    } catch (err) {
      toast.error(err instanceof Error ? err.message : "添加 tag 失败");
    } finally {
      setPending(false);
    }
  }

  async function handleRemove(tag: string) {
    setPending(true);
    try {
      await onRemoveTag(tag);
    } catch (err) {
      toast.error(err instanceof Error ? err.message : "删除 tag 失败");
    } finally {
      setPending(false);
    }
  }

  return (
    <section className="space-y-4 rounded-md border border-border/60 bg-muted/20 p-5">
      <div className="text-[11px] font-medium uppercase tracking-wide text-muted-foreground">
        AI 摘要
      </div>
      {summary ? (
        <div className="space-y-2 text-sm leading-6 text-foreground/90">
          {summary.split(/\n\n+/).map((para, i) => (
            <p key={i}>{para.trim()}</p>
          ))}
        </div>
      ) : (
        <p className="text-xs text-muted-foreground">（无摘要）</p>
      )}

      <div className="flex flex-wrap items-center gap-1.5 pt-1">
        {systemTags.map((t) => (
          <span
            key={t}
            className="rounded-full bg-muted px-2.5 py-0.5 font-mono text-[10px] text-muted-foreground"
            title="系统 tag"
          >
            {t}
          </span>
        ))}
        {topicTags.map((t) => (
          <span
            key={t}
            className="rounded-full bg-foreground/5 px-2.5 py-0.5 text-[11px] text-foreground/80"
            title="内容 tag"
          >
            {t}
          </span>
        ))}
        {userTags.map((t) => (
          <span
            key={t}
            className="inline-flex items-center gap-1 rounded-full bg-blue-100 px-2.5 py-0.5 text-[11px] font-medium text-blue-700 dark:bg-blue-950/40 dark:text-blue-300"
            title="我添加的 tag"
          >
            {t}
            <button
              type="button"
              disabled={pending}
              onClick={() => handleRemove(t)}
              className="ml-0.5 inline-flex h-3 w-3 items-center justify-center rounded-full hover:bg-blue-200/60 disabled:opacity-50 dark:hover:bg-blue-800/40"
              aria-label={`删除 tag ${t}`}
            >
              <X className="h-2.5 w-2.5" />
            </button>
          </span>
        ))}

        {adding ? (
          <form onSubmit={handleSubmit} className="inline-flex items-center gap-1">
            <input
              autoFocus
              value={draft}
              onChange={(e) => setDraft(e.target.value)}
              onBlur={() => {
                if (!draft.trim()) setAdding(false);
              }}
              onKeyDown={(e) => {
                if (e.key === "Escape") {
                  setDraft("");
                  setAdding(false);
                }
              }}
              disabled={pending}
              placeholder="新 tag（回车提交）"
              className="h-6 rounded-full border border-border/60 bg-background px-2.5 text-[11px] focus:border-blue-400 focus:outline-none"
            />
          </form>
        ) : (
          <button
            type="button"
            onClick={() => setAdding(true)}
            className="inline-flex items-center gap-1 rounded-full border border-dashed border-border/60 px-2.5 py-0.5 text-[11px] text-muted-foreground hover:border-foreground/40 hover:text-foreground"
          >
            + 添加
          </button>
        )}
      </div>
    </section>
  );
}


