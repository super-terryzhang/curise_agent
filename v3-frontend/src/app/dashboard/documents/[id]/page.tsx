const toUTC = (s: string) => s.endsWith("Z") || s.includes("+") ? s : s + "Z";
function formatTime(iso: string | null) {
  if (!iso) return "—";
  return new Date(toUTC(iso)).toLocaleString("zh-CN", {
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
    hour: "2-digit",
    minute: "2-digit",
  });
}

function resolvePreviewUrl(url: string | null) {
  if (!url) return null;
  if (url.startsWith("http://") || url.startsWith("https://")) return url;
  return `${API_BASE}${url}`;
}

// Backend file_type tags for spreadsheet-shaped binaries. Mirrors
// FILE_TYPE_TO_MIME in v3_backend/domains/document/file_types.py — "xlsx"
// kept for legacy rows pre-2026-05-01.
const SPREADSHEET_FILE_TYPES = new Set(["excel", "xlsx", "xls", "csv"]);
function isSpreadsheetType(t: string | null | undefined): boolean {
  return !!t && SPREADSHEET_FILE_TYPES.has(t);
}

function formatMetaValue(key: string, value: unknown): string {
  if (value === null || value === undefined || value === "") return "—";
  if (key === "total_amount" && typeof value === "number") {
    return value.toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 });
  }
  if (typeof value === "object") {
    // extra_fields or nested objects — pretty-print as JSON
    try {
      const s = JSON.stringify(value, null, 2);
      return s === "{}" || s === "[]" ? "—" : s;
    } catch {
      return "—";
    }
  }
  return String(value);
}

